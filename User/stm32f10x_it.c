/**
  ******************************************************************************
  * @file    stm32f10x_it.c
  * @brief   中断服务函数集合文件
  *
  * 文件说明：
  *   本文件包含 ARM Cortex-M3 内核的异常处理函数和 STM32 外设的中断服务函数。
  *   所有的异常/中断处理函数都放在这里统一管理。
  *
  * 什么是中断？
  *   中断是 CPU 在运行程序时，被内部或外部事件"打断"而跳去执行另一段
  *   特定代码（中断服务函数）的机制。处理完中断后再回到原来被打断的地方继续执行。
  *   相当于你在看书时，电话响了（中断），你放下书接电话（执行中断服务函数），
  *   接完电话后继续看书（返回主程序）。
  *
  * Cortex-M3 异常类型（按优先级从高到低）：
  *   - Reset        : 复位（上电/复位按钮触发）
  *   - NMI          : 不可屏蔽中断
  *   - HardFault    : 硬件错误（程序崩溃时进入）
  *   - MemManage    : 内存管理错误（访问非法内存地址）
  *   - BusFault     : 总线错误（访问外设失败）
  *   - UsageFault   : 用法错误（如除零、未对齐访问等）
  *   - SVC          : 系统服务调用（OS 中用于系统调用）
  *   - DebugMon     : 调试监控
  *   - PendSV       : 可挂起系统服务（OS 中用于任务切换）
  *   - SysTick      : 系统滴答定时器中断
  ******************************************************************************
  */

