/* ── 【新增】全局系统滴答毫秒计数器声明 ──
 * 由 main.c 定义，此处声明为 extern 以便在中断中访问。
 * 每 1ms 自动加 1，用于红外信号超时检测。
 */
extern volatile uint32_t g_sys_tick_ms;

/**
  * @brief  SysTick 系统滴答定时器处理函数
  *
  * SysTick 是 Cortex-M3 内核自带的一个24位递减定时器。
  *
  * 【修改说明】原本为空函数，现在用于维护一个1ms自由运行计数器。
  * SysTick 在 main.c 中通过 SysTick_Config() 配置为每1ms触发一次中断，
  * 此 ISR 每次被调用时 g_sys_tick_ms 自增1。
  *
  * 用途：为主循环中的红外信号超时检测提供时间基准。
  *
  * 注意：
  * - SysTick 中断优先级被配置为最低，不影响红外接收等关键中断
  * - 与 Delay.c 中的阻塞式延时兼容（Delay_us 会自动保存/恢复 SysTick 配置）
  */
void SysTick_Handler(void)
{
    g_sys_tick_ms++;    // 【新增】系统毫秒计数器自增
}

