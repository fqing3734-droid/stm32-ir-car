/**
  * @brief  硬件错误处理函数
  *
  * HardFault 是 Cortex-M3 中最重要的错误处理函数。
  * 当 CPU 遇到无法恢复的硬件错误时进入此函数，例如：
  *   - 访问不存在的内存地址
  *   - 执行未定义指令
  *   - 栈溢出
  *
  * 本函数中写了一个死循环 while(1)，意味着当硬件错误发生时，
  * 程序会停在这里不再继续执行（可以方便调试时查看问题现场）。
  *
  * 调试技巧：在 while(1) 处设置断点，当程序卡在这里时，
  * 可以查看调用栈和寄存器值，找到导致错误的原因。
  */
void HardFault_Handler(void)
{
    // 进入死循环 —— 硬件错误时锁定在此便于调试
    while (1)
    {
        // 如果程序进入这里，说明发生了硬件故障！
        // 常见原因：访问空指针、数组越界写、栈溢出等
    }
}

