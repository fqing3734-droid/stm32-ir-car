/**
  ******************************************************************************
  * @file    Key.c
  * @brief   独立按键输入检测模块
  *
  * 功能概述：
  *   检测单个独立按键的按下状态，包含软件消抖处理。
  *   按键连接在 PA15，采用上拉输入模式（按键按下→低电平，松开→高电平）。
  *
  * 硬件连接：
  *   - 按键一端接 PA15，另一端接 GND
  *   - PA15 配置为内部上拉输入（空闲时被内部上拉电阻拉到高电平）
  *
  * 按键抖动问题：
  *   机械按键在按下和松开瞬间，触点会产生多次快速通断（抖动），
  *   持续时间通常为 5~20ms。如果不处理抖动，一次按键可能被误读为多次按下。
  *
  * 消抖方法（本代码采用的方式）：
  *   1. 检测到低电平（按键可能被按下）
  *   2. 延时 20ms，等待抖动结束
  *   3. 再次检测：如果仍为低电平 → 确认按键确实被按下
  *   4. 等待按键松开（引脚回到高电平）
  *   5. 延时 20ms，等待松开时的抖动结束
  *   6. 返回键值
  ******************************************************************************
  */

#include "stm32f10x.h"    // STM32F10x 标准外设库头文件
#include "Delay.h"        // 延时函数（用于消抖）

/**
  * @brief  按键初始化函数
  * @param  无
  * @retval 无
  *
  * 配置 PA15 为上拉输入模式（Internal Pull-Up）
  * 特点：按键未按下时自动被内部上拉电阻拉为高电平，按下时接地变低电平
  */
void Key_Init(void)
{
    // --- 1. 开启 GPIOA 时钟 ---
    RCC_APB2PeriphClockCmd(RCC_APB2Periph_GPIOA, ENABLE);

    // --- 2. 配置 PA15 为上拉输入 ---
    GPIO_InitTypeDef GPIO_InitStructure;
    GPIO_InitStructure.GPIO_Mode  = GPIO_Mode_IPU;      // 上拉输入（默认高电平）
    GPIO_InitStructure.GPIO_Pin   = GPIO_Pin_15;        // 使用 PA15 引脚
    GPIO_InitStructure.GPIO_Speed = GPIO_Speed_50MHz;   // 输入模式速度设置无实际作用
    GPIO_Init(GPIOA, &GPIO_InitStructure);
}

/**
  * @brief  按键扫描函数（带消抖处理）
  * @param  无
  * @retval KeyNum: 0=无按键按下, 1=检测到一次按键按下
  *
  * 工作流程（完整消抖状态机）：
  *   1. 读取 PA15 电平
  *   2. 如果是高电平（1）→ 按键未按下 → 返回 0
  *   3. 如果是低电平（0）→ 可能被按下 → 延时 20ms 后再次检查
  *   4. 延时后仍为低电平 → 确认为有效按键
  *   5. 等待按键松开（while 循环等待高电平）
  *   6. 松开后再延时 20ms（消除松开时的抖动）
  *   7. 返回 1，表示检测到一次完整的按键动作
  *
  * 注意：这是个"阻塞式"函数！等待按键松开期间（步骤5），程序会卡在这里
  *       直到按键松开，所以不适合需要并行处理多任务的场景
  */
uint8_t Key_GetNum(void)
{
    uint8_t KeyNum = 0;    // 按键返回值，默认 0（无按键）

    // --- 检测按键是否被按下（低电平有效）---
    if (GPIO_ReadInputDataBit(GPIOA, GPIO_Pin_15) == 0)
    {
        Delay_ms(20);       // 延时 20ms，等待按键抖动结束（消抖）

        // 再次确认：如果仍然是低电平 → 确实被按下了（不是抖动）
        // 等待按键松开：while 循环条件为真时死等，直到引脚恢复高电平
        while (GPIO_ReadInputDataBit(GPIOA, GPIO_Pin_15) == 0)
        {
            // 此处可添加超时保护，避免按键卡死导致程序永久阻塞
        }

        Delay_ms(20);       // 松开后延时 20ms，消除松开时的抖动
        KeyNum = 1;         // 确认是一次有效的按键
    }

    return KeyNum;
}
